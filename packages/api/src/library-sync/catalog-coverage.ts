/**
 * Every column of every content model, and every key of every JSON definition,
 * claimed by a sync unit or excluded with a reason (merge unit catalog §4, §6).
 * `catalog-coverage.spec.ts` fails when the schema grows a field this table
 * does not mention, so nothing new is silently left out of sync.
 */

