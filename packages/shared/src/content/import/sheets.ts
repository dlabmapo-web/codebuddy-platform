/**
 * A header cell, reduced enough to survive a spreadsheet round trip.
 *
 * Case and whitespace only. `Module_Key` and `module key` reach the same
 * column because Excel's own autocorrect and a person's shift key produce both,
 * and neither is ambiguous. `module` does not, and neither does `모듈 키`: §5.1
 * refuses to infer a required column from an approximate spelling, because the
 * cost of guessing wrong is importing a column of titles as identities.
 */
export function normalizeColumnName(cell: string): string {
  return cell.normalize("NFKC").trim().toLowerCase().replace(/[\s_]+/g, "_");
}

export type ColumnIndex<Column extends string> = Partial<
  Record<Column, number>
>;

/**
 * Where each known column sits, by name rather than by position.
 *
 * Columns are addressed by name throughout, so a Team Lead who inserts their
 * own `notes` column in the middle of the sheet does not shift every value one
 * place to the right. §5.1 ignores unknown columns and reports them as a
 * warning, which is exactly what "you added something we will not import"
 * should feel like.
 *
 * A duplicate canonical column keeps the *first*, and the caller reports it. Two
 * columns called `problem_key` is a file somebody built by pasting two exports
 * together, and silently preferring the last one imports the half they were not
 * looking at.
 */
export function indexHeaderRow<Column extends string>(
  cells: readonly string[],
  known: readonly Column[],
): { columns: ColumnIndex<Column>; unknown: string[]; duplicated: Column[] } {
  const columns: ColumnIndex<Column> = {};
  const unknown: string[] = [];
  const duplicated: Column[] = [];

  cells.forEach((cell, index) => {
    const normalized = normalizeColumnName(cell);
    if (normalized.length === 0) return;
    const match = known.find((column) => column === normalized);
    if (!match) {
      unknown.push(cell.trim());
      return;
    }
    if (columns[match] !== undefined) {
      if (!duplicated.includes(match)) duplicated.push(match);
      return;
    }
    columns[match] = index;
  });

  return { columns, unknown, duplicated };
}

/** Missing required columns, in the order the template declares them. */
export function missingRequiredColumns<Column extends string>(
  columns: ColumnIndex<Column>,
  required: readonly Column[],
): Column[] {
  return required.filter((column) => columns[column] === undefined);
}

/**
 * One cell, by column name, or the empty string.
 *
 * A sparse row — one where the author cleared the trailing cells — is shorter
 * than the header, and every caller wants "" rather than undefined for that.
 */
export function cellAt<Column extends string>(
  row: readonly string[],
  columns: ColumnIndex<Column>,
  column: Column,
): string {
  const index = columns[column];
  if (index === undefined) return "";
  return row[index] ?? "";
}

/**
 * The `template_version` value, read from the Instructions sheet.
 *
 * The sheet is prose for a person, so the version is found by scanning for the
 * label rather than by reading a fixed cell: an author who adds a paragraph
 * above it must not invalidate their own workbook. The label itself is
 * canonical and untranslated for the same reason the column names are.
 */
export function readTemplateVersion(rows: readonly string[][]): number | null {
  for (const row of rows) {
    const labelIndex = row.findIndex(
      (cell) => normalizeColumnName(cell) === "template_version",
    );
    if (labelIndex === -1) continue;
    for (const cell of row.slice(labelIndex + 1)) {
      const value = cell.trim();
      if (value.length === 0) continue;
      const parsed = Number.parseInt(value, 10);
      return Number.isSafeInteger(parsed) && parsed > 0 ? parsed : null;
    }
  }
  return null;
}
