/**
 * The workbook's machine interface: which sheets exist, and what each column is
 * called.
 *
 * §5.1 makes one decision that shapes this whole file — **sheet and column
 * names are not localized.** The Instructions sheet is translated, the wizard
 * around it is translated, and the header row is English snake_case in both
 * languages. A Korean Team Lead and an English one exchange one workbook, and
 * neither of them has to know which language the other's Excel was installed
 * in.
 *
 * The other decision is that names are exact. The member importer accepts
 * `Email`, `E-mail`, and `이메일` for one column, because that file comes out of
 * a school's own system and Cove has no say in what it looks like. This one is
 * generated by Cove and edited in place: a header that no longer matches means
 * the row was edited by hand into something ambiguous, and §5.1 says an
 * approximate spelling is a rejection rather than a guess.
 *
 * See §5.1 and §5.3–5.6 of the team lead Excel problem import design.
 */

